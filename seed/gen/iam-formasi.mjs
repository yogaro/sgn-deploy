// Writes sql/20_iam_roles.sql for the FORMASI demo: the shared demo password and ACTIVE status for every FORMASI person and
// the demo accounts, the one Admin L&D account, and the LMS roles given by job title (the table below). Prints who gets which role; nothing is applied
// here, so the list can be checked before the SQL runs. Run: node seed/gen/iam-formasi.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const here = new URL('..', import.meta.url).pathname
const staff = JSON.parse(readFileSync(`${here}data/private/formasi.json`, 'utf8'))
const hash = process.env.SEED_PASSWORD_HASH || '$2y$12$5/g01JYXQiaTc0pBYP3cY.BF0OrVr6Q/oQf3LPbsO.84kQ8ASeY.y'
if (!/^\$2[aby]\$\d\d\$[./A-Za-z0-9]{53}$/.test(hash)) throw new Error('SEED_PASSWORD_HASH is not a bcrypt hash')
// Employees change the shared first password at first login (seed/run.sh SEED_MUST_CHANGE); the admin account never does.
const mustChange = process.env.SEED_MUST_CHANGE === '1'
// LMS is managed from one account that is not an employee (PO 2026-11-17), so the SDM staff who also learn keep a plain
// learner menu. The account has no employee record and is kept by 00_reset_iam.sql.
export const ADMIN_EMAIL = 'admin.lms@sgn.example'
// USER_ADMIN lets the same account manage employee accounts from LMS (PO 2026-11-18): reset password, lock, disable.
const adminRoles = ['LMS_ADMIN', 'LMS_REPORTER', 'USER_ADMIN']

// role -> [FORMASI unit, job title pattern]
const rules = {
  LMS_ADMIN: [],
  LMS_REPORTER: [
    ['HO SGN - BOD', /^Direktur Utama$/i],
    ['HO SGN - BOD', /^Direktur SDM dan Teknologi Informasi$/i],
    ['HO SGN - Divisi Pengembangan SDM & Budaya', /^Kadiv Pengembangan SDM & Budaya$/i],
    ['HO SGN - Divisi Operasional SDM', /^Kadiv Operasional SDM$/i],
  ],
  LMS_FINANCE_APPROVER: [['HO SGN - Divisi Perbendaharaan & Anggaran', /^Kadiv Perbendaharaan/i]],
  TRAINER: [['HO SGN - Divisi Pengembangan SDM & Budaya', /^Kasubdiv Pendidikan & Pelatihan$/i]],
}

const holders = {}
for (const [role, list] of Object.entries(rules)) {
  holders[role] = staff.filter((s) => list.some(([unit, re]) => s.unit === unit && re.test(s.position)))
}
const numbers = [...staff.map((s) => s.pn), ...['SPI', 'TEKPOL', 'SEKPER', 'K3', 'TANAMAN', 'SDM', 'LITBANG'].map((u) => `DEMO-${u}-01`)]
let sql = '-- Generated by seed/gen/iam-formasi.mjs. Idempotent.\nBEGIN;\n'
sql += 'CREATE TEMP TABLE demo_people (num text PRIMARY KEY);\n'
for (let i = 0; i < numbers.length; i += 2000) sql += `INSERT INTO demo_people VALUES ${numbers.slice(i, i + 2000).map((n) => `('${n}')`).join(', ')};\n`
sql += `UPDATE iam.users u SET password_hash = '${hash}', status = 'ACTIVE', must_change_password = ${mustChange}, password_changed_at = now(), failed_attempts = 0, locked_until = NULL
FROM iam.employees e JOIN demo_people d ON d.num = e.employee_number WHERE e.id = u.employee_id;\n`
sql += `DELETE FROM iam.user_roles ur USING iam.roles r WHERE ur.role_id = r.id AND r.code IN (${Object.keys(rules).map((r) => `'${r}'`).join(', ')});\n`
for (const [role, people] of Object.entries(holders)) {
  if (!people.length) continue
  sql += `INSERT INTO iam.user_roles (user_id, role_id)
SELECT u.id, r.id FROM iam.users u JOIN iam.employees e ON e.id = u.employee_id, iam.roles r
WHERE r.code = '${role}' AND e.employee_number IN (${people.map((p) => `'${p.pn}'`).join(', ')})
ON CONFLICT DO NOTHING;\n`
}
const ADMIN_LOGIN = ADMIN_EMAIL.split('@')[0].replace(/\./g, '-').toUpperCase()
sql += `INSERT INTO iam.users (login_id, email, password_hash, status, must_change_password, password_changed_at)
VALUES ('${ADMIN_LOGIN}', '${ADMIN_EMAIL}', '${hash}', 'ACTIVE', false, now())
ON CONFLICT (email) DO UPDATE SET password_hash = EXCLUDED.password_hash, status = 'ACTIVE', must_change_password = false,
  failed_attempts = 0, locked_until = NULL;
INSERT INTO iam.user_roles (user_id, role_id)
SELECT u.id, r.id FROM iam.users u, iam.roles r WHERE u.email = '${ADMIN_EMAIL}' AND r.code IN (${adminRoles.map((r) => `'${r}'`).join(', ')})
ON CONFLICT DO NOTHING;
`
sql += 'COMMIT;\n'
writeFileSync(`${here}sql/20_iam_roles.sql`, sql)
console.log(`Admin L&D: ${ADMIN_LOGIN} (${ADMIN_EMAIL}; ${adminRoles.join(', ')}), bukan karyawan`)
for (const [role, people] of Object.entries(holders)) {
  console.log(`\n${role} (${people.length})`)
  for (const p of people) console.log(`  ${p.pn}  ${p.name}  ·  ${p.position}  ·  ${p.unit.replace('HO SGN - ', '')}`)
}
