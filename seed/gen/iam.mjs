// Writes sql/20_iam_roles.sql: the shared demo password, ACTIVE status and the LMS personas' roles. Run on db_iam.
import { writeFileSync } from 'node:fs'

const hash = '$2y$12$5/g01JYXQiaTc0pBYP3cY.BF0OrVr6Q/oQf3LPbsO.84kQ8ASeY.y'
const personas = {
  LMS_ADMIN: ['PTSGN-1034', 'PTSGN-1035', 'PTSGN-1036'],
  LMS_REPORTER: ['PTSGN-1034', 'PTSGN-1007', 'PTSGN-1011', 'PTSGN-1001'],
  LMS_FINANCE_APPROVER: ['PTSGN-1008', 'PTSGN-1010'],
  TRAINER: ['PTSGN-1037', 'PTSGN-1038', 'PTSGN-1039', 'PTSGN-1043', 'PTSGN-1028', 'PTSGN-1025', 'PTSGN-1041'],
}
let sql = '-- Generated by seed/gen/iam.mjs. Idempotent.\nBEGIN;\n'
sql += `UPDATE iam.users u SET password_hash = '${hash}', status = 'ACTIVE', must_change_password = false, password_changed_at = now(), failed_attempts = 0, locked_until = NULL
FROM iam.employees e WHERE e.id = u.employee_id AND e.employee_number LIKE 'PTSGN-%';\n`
for (const [role, numbers] of Object.entries(personas)) {
  sql += `INSERT INTO iam.user_roles (user_id, role_id)
SELECT u.id, r.id FROM iam.users u JOIN iam.employees e ON e.id = u.employee_id, iam.roles r
WHERE r.code = '${role}' AND e.employee_number IN (${numbers.map((n) => `'${n}'`).join(', ')})
ON CONFLICT DO NOTHING;\n`
}
sql += 'COMMIT;\n'
writeFileSync(new URL('../sql/20_iam_roles.sql', import.meta.url), sql)
